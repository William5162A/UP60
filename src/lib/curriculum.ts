export const SUBJECTS: Subject[] = Object.entries(RAW).flatMap(([key, rows]) => {
  const [y, s] = key.split("-").map(Number) as [Year, Semester];
  return rows.map(([name, description, price], i) => ({
    id: `y${y}s${s}-${String(i + 1).padStart(2, "0")}`,
    name,
    year: y,
    semester: s,
    description,
    price,
    order: (y * 10 + s) * 100 + i,
  }));
});

